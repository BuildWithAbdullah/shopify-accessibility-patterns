/* ---------------------------------------------------------------------------
   liquid-contract.mjs
   The guarantees each snippet in snippets/ makes, asserted against the snippet.

   A snippet library is a set of claims about markup that does not exist yet.
   These assertions turn each claim into something CI can check: that the icon
   button always carries a name, that the product card can never emit a control
   inside a link, that the variant picker is a real radio group, that the skip
   link stays focusable.

   The limits are worth being plain about. Nothing here executes Liquid, so the
   assertions are made against a skeleton with the Liquid stripped and every
   branch of every conditional kept at once. That answers "can this snippet ever
   emit X" and cannot answer "what does it render for this product". Liquid
   output is opaque: an id generated by assign is a placeholder, so a check that
   a label's `for` matches an input's `id` is checking that both attributes are
   present and not that they agree. What a nested snippet emits is that
   snippet's business, and for the icon glyph that snippet is the theme's.
   --------------------------------------------------------------------------- */

import { readFileSync } from 'node:fs';
import { parse as parseLiquid, includeTags, namesLiteralSnippet, branchSegments } from './liquid.mjs';
import { parse as parseHtml, byName, elements, attr, hasAttr, classList, textOf } from './html.mjs';
import { parse as parseCss, declared, rulesWhere } from './css.mjs';
import { run as runChecks } from './checks.mjs';

/**
 * Outputs whose source is text a merchant types into the admin, or a value
 * passed into the snippet, and which therefore has to be escaped before it
 * lands in markup.
 */
const NEEDS_ESCAPING = /(^|\.)(title|name|alt)$|^(label|value)$/;
const ESCAPING_FILTERS = new Set(['escape', 'escape_once', 'strip_html', 'json', 't', 'money', 'image_tag']);

function result(id, ok, detail, line) {
  return { id, ok, detail, line };
}

/* -------------------------------------------------------------------------
   Guarantees that hold for every snippet
   ------------------------------------------------------------------------- */

export function auditCommon(name, source) {
  const parsed = parseLiquid(source);
  const out = [];

  /* Liquid's render tag takes a literal filename. It does not accept a
     variable and it does not accept a filtered expression, so
     {% render 'icon-' | append: icon %} resolves to nothing and renders
     nothing, silently. */
  const bad = includeTags(parsed).filter((tag) => !namesLiteralSnippet(tag));
  out.push(
    result(
      `${name}:render-names-a-literal`,
      bad.length === 0,
      bad.length
        ? `${bad.map((tag) => tag.raw).join(' | ')} does not name a snippet with a string literal, so it renders nothing`
        : 'every render and include names a snippet with a string literal',
      bad[0]?.line
    )
  );

  /* Merchant text reaching markup unescaped. */
  const unescaped = parsed.outputs.filter((output) => {
    if (!NEEDS_ESCAPING.test(output.expression.trim())) return false;
    return !output.filters.some((filter) => ESCAPING_FILTERS.has(filter.name));
  });
  out.push(
    result(
      `${name}:merchant-text-escaped`,
      unescaped.length === 0,
      unescaped.length
        ? `${unescaped.map((o) => o.raw).join(' | ')} puts merchant-editable text into markup without escaping it`
        : 'every merchant-editable value passes through an escaping filter',
      unescaped[0]?.line
    )
  );

  /* A snippet's own style block must not use a hiding technique that takes
     content out of the accessibility tree, because the whole point of the
     visually hidden pattern is that it does not. */
  const styleRules = parsed.styles.flatMap((block) =>
    parseCss(block.body).map((rule) => ({ ...rule, line: block.line + rule.line - 1 }))
  );
  const hides = styleRules.filter(
    (rule) => declared(rule, 'display') === 'none' || declared(rule, 'visibility') === 'hidden'
  );
  out.push(
    result(
      `${name}:no-accessibility-tree-hiding`,
      hides.length === 0,
      hides.length
        ? `${hides.map((rule) => rule.selectors.join(', ')).join(' | ')} uses display:none or visibility:hidden`
        : 'no rule in the snippet removes content from the accessibility tree',
      hides[0]?.line
    )
  );

  /* No aria-label where visible or visually hidden text is available, because
     aria-label is not translated by browser page translation and breaks voice
     control when it differs from the visible label. */
  out.push(
    result(
      `${name}:no-aria-label-for-naming`,
      !/\baria-label\s*=/.test(parsed.skeleton),
      'these snippets name controls with text, not aria-label: text is translated by page translation, survives a failed icon set, and is what a voice control user can say',
      undefined
    )
  );

  return { parsed, out };
}

/* -------------------------------------------------------------------------
   Per snippet guarantees
   ------------------------------------------------------------------------- */

const SNIPPET_CHECKS = {
  'a11y-icon-button'(parsed) {
    const doc = parseHtml(parsed.skeleton);
    const out = [];
    const buttons = byName(doc, 'button');

    out.push(
      result(
        'icon-button:is-a-button',
        buttons.length === 1 && (attr(buttons[0], 'type') || '').toLowerCase() === 'button',
        'one <button type="button">: without the type it defaults to submit and posts whatever form it happens to sit inside, which on a product page is the add-to-cart form',
        buttons[0]?.line
      )
    );

    const hiddenLabel = elements(doc).find((el) => classList(el).includes('visually-hidden'));
    out.push(
      result(
        'icon-button:carries-hidden-text',
        Boolean(hiddenLabel) && textOf(hiddenLabel).trim() !== '',
        'the accessible name comes from a visually hidden span inside the button',
        hiddenLabel?.line
      )
    );

    out.push(
      result(
        'icon-button:target-size',
        styleDeclares(parsed, '.a11y-icon-button', 'min-width', 24) &&
          styleDeclares(parsed, '.a11y-icon-button', 'min-height', 24),
        'the target is at least 24 by 24 CSS pixels, which is 2.5.8 at Level AA. The glyph is not resized; the hit area is',
        undefined
      )
    );

    return out;
  },

  'a11y-product-card'(parsed) {
    const out = [];
    const doc = parseHtml(parsed.skeleton);

    const nested = runChecks(parsed.skeleton, ['nested-interactive']);
    out.push(
      result(
        'product-card:no-nested-interactive',
        nested.length === 0,
        nested.length
          ? nested.map((f) => f.evidence).join(' | ')
          : 'no branch of this snippet can emit a control inside a link, which is the defect it replaces',
        nested[0]?.line
      )
    );

    const links = byName(doc, 'a').filter((el) => hasAttr(el, 'href'));
    out.push(
      result(
        'product-card:title-is-the-link',
        links.length === 1 && links[0].parent && links[0].parent.name === 'h3',
        'one link, and it is the product title inside the heading, so a screen reader listing links hears product names rather than twenty-four identical ones',
        links[0]?.line
      )
    );

    const buttons = byName(doc, 'button');
    const addButton = buttons.find((el) => classList(el).some((c) => c.includes('add')));
    const hiddenSuffix =
      addButton &&
      addButton.children.some(
        (child) => child.type === 'element' && classList(child).includes('visually-hidden')
      );
    out.push(
      result(
        'product-card:add-button-is-distinguishable',
        Boolean(hiddenSuffix),
        'the quick add button carries hidden text naming the product, so a grid of them is not twenty-four controls called "Quick add"',
        addButton?.line
      )
    );

    /* Checked per branch rather than on the flattened skeleton. On the
       skeleton the hidden "Price" label from the else branch sits beside the
       struck price from the if branch and satisfies the check without ever
       rendering with it, which is exactly the false pass a flattened template
       invites. */
    const colourOnly = branchSegments(parsed.source).flatMap((segment) =>
      runChecks(segment, ['meaning-in-colour-only'])
    );
    out.push(
      result(
        'product-card:price-state-has-text',
        colourOnly.length === 0,
        colourOnly.length
          ? colourOnly.map((f) => f.evidence).join(' | ')
          : 'in every branch that renders a struck or sale-coloured price, a hidden label names it, because a screen reader does not announce a line through a number',
        colourOnly[0]?.line
      )
    );

    return out;
  },

  'a11y-variant-picker'(parsed) {
    const out = [];
    const doc = parseHtml(parsed.skeleton);

    const fieldsets = byName(doc, 'fieldset');
    const legends = byName(doc, 'legend');
    out.push(
      result(
        'variant-picker:grouped-and-named',
        fieldsets.length >= 1 && legends.length >= 1 && legends[0].parent?.name === 'fieldset',
        'a fieldset with a legend, so the option name is announced when the group is entered rather than left to be guessed from the swatches',
        fieldsets[0]?.line
      )
    );

    const inputs = byName(doc, 'input');
    out.push(
      result(
        'variant-picker:native-radios',
        inputs.length >= 1 && inputs.every((el) => (attr(el, 'type') || '').toLowerCase() === 'radio'),
        'native radio inputs, which bring arrow-key movement, one tab stop for the group and the selected state announced, none of which a div can be given for free',
        inputs[0]?.line
      )
    );

    const labels = byName(doc, 'label');
    out.push(
      result(
        'variant-picker:every-input-labelled',
        inputs.length >= 1 &&
          inputs.every((el) => hasAttr(el, 'id')) &&
          labels.length >= inputs.length &&
          labels.every((el) => hasAttr(el, 'for')),
        'every input has an id and every label has a for. Both values are Liquid, so this asserts the attributes are present and not that they agree: that part is read, not checked',
        inputs[0]?.line
      )
    );

    out.push(
      result(
        'variant-picker:value-is-text',
        labels.every((el) => textOf(el).trim() !== ''),
        'the option value is text in the label, because a coloured square on its own conveys its value by colour and nothing else',
        labels[0]?.line
      )
    );

    out.push(
      result(
        'variant-picker:selection-not-colour-alone',
        styleSelectorHas(parsed, ':checked', 'border-width'),
        'the selected state changes more than a colour, so it survives greyscale and forced colours',
        undefined
      )
    );

    return out;
  },

  'a11y-skip-link'(parsed) {
    const out = [];
    const doc = parseHtml(parsed.skeleton);
    const link = byName(doc, 'a')[0];

    out.push(
      result(
        'skip-link:points-at-a-fragment',
        Boolean(link) && (attr(link, 'href') || '').startsWith('#'),
        'the link points at a fragment. Whether the target exists and can take focus is a property of layout/theme.liquid, not of this snippet, and it is checked in examples/skip-link-unusable',
        link?.line
      )
    );

    out.push(
      result(
        'skip-link:offset-not-hidden',
        styleSelectorHas(parsed, '.a11y-skip-link', 'transform'),
        'offset off screen with a transform rather than hidden, so it stays in the tab order and can be reached at all',
        undefined
      )
    );

    out.push(
      result(
        'skip-link:returns-on-focus',
        styleSelectorHas(parsed, '.a11y-skip-link:focus', 'transform'),
        'brought back on focus, so a sighted keyboard user can see where they are',
        undefined
      )
    );

    out.push(
      result(
        'skip-link:focus-not-focus-visible',
        styleRules(parsed).some((rule) => rule.selectors.includes('.a11y-skip-link:focus')),
        ':focus rather than :focus-visible here. The link is only ever reached by keyboard, and :focus-visible support in older in-app webviews is the one case where the difference costs a user the control',
        undefined
      )
    );

    return out;
  }
};

/* ------------------------------------------------------------------------- */

function styleRules(parsed) {
  return parsed.styles.flatMap((block) =>
    parseCss(block.body).map((rule) => ({ ...rule, line: block.line + rule.line - 1 }))
  );
}

function styleDeclares(parsed, selector, property, atLeast) {
  const rules = rulesWhere(styleRules(parsed), (s) => s.includes(selector));
  for (const rule of rules) {
    const value = declared(rule, property);
    if (value === undefined) continue;
    const px = Number(String(value).replace('px', ''));
    if (Number.isFinite(px) && px >= atLeast) return true;
  }
  return false;
}

function styleSelectorHas(parsed, selectorFragment, property) {
  return rulesWhere(styleRules(parsed), (s) => s.includes(selectorFragment)).some(
    (rule) => declared(rule, property) !== undefined
  );
}

/** Audit one snippet file. */
export function auditSnippet(path) {
  const name = path.split('/').pop().replace(/\.liquid$/, '');
  const source = readFileSync(path, 'utf8');
  const { parsed, out } = auditCommon(name, source);
  const specific = SNIPPET_CHECKS[name];
  if (specific) out.push(...specific(parsed));
  return out;
}

export const SNIPPETS_WITH_CONTRACTS = Object.keys(SNIPPET_CHECKS);
