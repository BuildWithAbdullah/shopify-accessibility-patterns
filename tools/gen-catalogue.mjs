#!/usr/bin/env node
/* ---------------------------------------------------------------------------
   gen-catalogue.mjs
   Writes docs/09-finding-catalogue.md from tools/findings.mjs and
   tools/limits.mjs.

   Run it as `node tools/gen-catalogue.mjs`, never through npm. `npm run`
   prints its own banner on stdout, so a CI step that redirects the output
   into a file captures two lines of npm before the content and the generated
   file never matches the one in the repository. It passes locally, where
   whoever wrote it ran the script directly, which is how that survives
   review. This script sidesteps the question by writing the file itself and
   printing one status line to stderr.
   --------------------------------------------------------------------------- */

import { writeFileSync, readFileSync, realpathSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { FINDINGS, checkOf } from './findings.mjs';
import { LIMITS } from './limits.mjs';
import { CHECKS, runByCode } from './checks.mjs';
import { FIXTURES } from '../test/fixtures/index.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'docs', '09-finding-catalogue.md');

const manifest = JSON.parse(readFileSync(join(root, 'examples', 'manifest.json'), 'utf8'));

/** Where each finding has been observed firing, which is asserted separately. */
function observations() {
  const where = new Map();
  const note = (code, place) => where.set(code, [...(where.get(code) ?? []), place]);
  for (const entry of manifest.examples) {
    for (const code of entry.onFail) note(code, `\`examples/${entry.directory}\``);
  }
  for (const fixture of FIXTURES) {
    const html = readFileSync(join(root, 'test', 'fixtures', fixture.file), 'utf8');
    for (const code of runByCode(html).keys()) note(code, `\`test/fixtures/${fixture.file}\``);
  }
  return where;
}

export function buildCatalogue() {
  const where = observations();
  const fromPairs = new Set(manifest.examples.flatMap((e) => e.onFail));

  const lines = [
    '# Finding catalogue',
    '',
    `Every finding the detectors in [\`tools/checks.mjs\`](../tools/checks.mjs) can`,
    `report: ${FINDINGS.length} of them, across ${CHECKS.length} checks.`,
    '',
    'This file is generated by `node tools/gen-catalogue.mjs` from',
    '[`tools/findings.mjs`](../tools/findings.mjs) and',
    '[`tools/limits.mjs`](../tools/limits.mjs). Edit those, not the tables. CI',
    'regenerates it and fails if the result differs, so the prose here cannot',
    'drift away from the code it describes.',
    '',
    'A check is not a finding, and the distinction is the reason this file',
    'exists. Eleven checks reported findings labelled with the check id alone,',
    `and the eleven example pairs reached ${fromPairs.size} of the ${FINDINGS.length} reasons below.`,
    'The rest had never been observed firing. Writing the fixtures that reach',
    'them turned up nine defects in the detectors, seven of which were in',
    'branches no pair touched.',
    '',
    'The third column is the one to read. Each finding says what it cannot',
    'establish, because the fix column is worthless without it: a finding is a',
    'shape in a file, not a measurement of what a visitor experiences.',
    '',
    'Every finding here is observed firing on a real page in CI. The last',
    'column says where, and `test/catalogue.mjs` asserts that set against this',
    'catalogue in both directions, so a finding cannot sit here having never',
    'fired and a detector cannot emit one nothing describes.',
    ''
  ];

  for (const check of CHECKS) {
    const mine = FINDINGS.filter((f) => checkOf(f.code) === check.id);
    lines.push(`## ${check.title}`, '');
    lines.push(`\`${check.id}\`, ${check.criteria.map((c) => `WCAG ${c}`).join(', ')}.`, '');
    lines.push(`${check.proves}`, '');
    lines.push('| Finding | Fix | What it cannot say | Observed in |');
    lines.push('|---|---|---|---|');
    for (const finding of mine) {
      const reason = finding.code.slice(finding.code.indexOf('/') + 1);
      const seen = (where.get(finding.code) ?? []).join(', ') || 'nowhere';
      lines.push(
        `| **\`${reason}\`**<br>${finding.summary} | ${finding.fix} | ${finding.cannotSay} | ${seen} |`
      );
    }
    lines.push('');
  }

  lines.push('## The limits of all of it', '');
  lines.push(
    'These are asserted rather than described. Each one is exercised in',
    '[`test/gap.mjs`](../test/gap.mjs) under its own id, and `tools/verify.mjs`',
    'asserts that the two files name the same set.',
    '',
    'A limit marked **both** is the strongest form: the same outcome for a',
    'visitor gets either verdict depending on something that is not a property',
    'of the page, so the finding count carries no information about that',
    'outcome at all.',
    '',
    '| Limit | Direction | Bounds | The claim |',
    '|---|---|---|---|'
  );
  for (const limit of LIMITS) {
    lines.push(
      `| \`${limit.id}\` | ${limit.directions} | ${limit.bounds.map((b) => `\`${b}\``).join(', ')} | ${limit.claim} |`
    );
  }
  lines.push('');
  lines.push(
    'The long form of the argument, with the parts no assertion reaches, is in',
    '[what the checks do not see](08-what-the-checks-do-not-see.md).',
    ''
  );

  return lines.join('\n');
}

/* Writing is guarded so that tools/verify.mjs can import buildCatalogue and
   compare its result against the file on disk without rewriting the file it
   is checking. A verifier that regenerates its own subject always passes. */
const invokedDirectly =
  process.argv[1] !== undefined &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  writeFileSync(OUT, buildCatalogue(), 'utf8');
  process.stderr.write(
    `docs/09-finding-catalogue.md written: ${FINDINGS.length} findings, ${LIMITS.length} limits\n`
  );
}

export { OUT };
